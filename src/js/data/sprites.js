export function buildSpriteRegistry() {
  const S = {};
  for (const a of ASSETS) S[a.key] = spriteCanvas(a.grid, a.map);

  // Tinted realm variants
  const tints = {
    red: -10, blue: 200, green: 120, purple: 280, cyan: 160,
    orange: 20, pink: 330, sand: 45, void: 260, forest: 90,
    ice: 200, infernal: 15, ash: -20,
  };
  for (const base of ['ghost', 'crawler', 'brute', 'caster', 'flyer', 'blob', 'summoner', 'knight', 'hound', 'egg']) {
    for (const t of Object.keys(tints)) {
      S[base + '_' + t] = tintCanvas(S[base], tints[t]);
    }
  }
  // Giant elite variants (2x scale)
  const giantBases = [
    { key: 'bruteGiant', grid: bruteBase, map: bruteMap },
    { key: 'blobGiant', grid: blobBase, map: blobMap },
    { key: 'ghostGiant', grid: ghostBase, map: ghostMap },
    { key: 'houndGiant', grid: houndBase, map: houndMap },
  ];
  for (const g of giantBases) S[g.key] = spriteCanvas(scaleGrid(g.grid, 2), g.map);

  return S;
}

